#!/usr/bin/env node
/**
 * Refresh the pinned ASAM checker-bundle rule lists in this directory.
 *
 * Each `*.bundle.json` here is a **pinned, checksummed transcript** of one ASAM
 * checker bundle's `checker_bundle_doc.md` — the bundle's own generated
 * documentation, which is the authoritative list of the checkers it implements
 * and the rule UIDs each addresses. The manifests exist so this repo can *gate*
 * on rule identity (a UID we attribute a gap to must be one a bundle really
 * publishes) without a network call or a submodule checkout at test time.
 *
 * This mirrors the discipline of `packages/authoring-wasm/native/verify-checksum.mjs`:
 * a third-party artifact is pinned by commit, verified by hash, and refreshed by
 * an explicit, reviewable command — never fetched implicitly.
 *
 * Usage:
 *   node packages/authoring-gate/qc-bundles/refresh.mjs            # rewrite the manifests at their pinned commits
 *   node packages/authoring-gate/qc-bundles/refresh.mjs --check    # verify only; non-zero exit if stale
 *
 * To bump a bundle: edit its `commit` field, run the command, review the diff.
 */
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const CHECK_ONLY = process.argv.includes('--check')

/** A rule UID: `<entity>:<standard>:<version>:<rule_set>.<name>`. */
const UID = /^[a-z0-9.-]+:[a-z0-9]+:[0-9.]+:[a-z0-9_]+\.[a-z0-9_.]+$/

/**
 * Parse a bundle's `checker_bundle_doc.md` into `{ buildVersion, checkers }`.
 * The format is generated by the qc-framework's own doc writer: a `## Checkers`
 * section, one `### <checker_name>` per checker, each with a `* Description:`
 * line and an `* Addressed rules:` list.
 */
function parseBundleDoc(markdown) {
  const buildVersion = /^\*\s+Build version:\s+(.+)$/m.exec(markdown)?.[1]?.trim()
  const checkers = []
  for (const section of markdown.split(/^### /m).slice(1)) {
    const lines = section.split('\n')
    const name = lines[0]?.trim()
    if (!name) continue
    const description = /^\*\s+Description:\s+(.+)$/m.exec(section)?.[1]?.trim() ?? ''
    const rules = []
    let inRules = false
    for (const line of lines.slice(1)) {
      if (/^\*\s+Addressed rules:/.test(line)) {
        inRules = true
        continue
      }
      const bullet = /^\s+\*\s+(\S+)\s*$/.exec(line)
      if (inRules && bullet?.[1]) rules.push(bullet[1])
      else if (inRules && line.trim() !== '') inRules = false
    }
    checkers.push({ name, description, rules })
  }
  return { buildVersion, checkers }
}

let stale = 0
for (const file of readdirSync(HERE)
  .filter((f) => f.endsWith('.bundle.json'))
  .sort()) {
  const path = join(HERE, file)
  const manifest = JSON.parse(readFileSync(path, 'utf8'))
  const url = `https://raw.githubusercontent.com/${manifest.repo}/${manifest.commit}/${manifest.source}`

  const response = await fetch(url)
  if (!response.ok) throw new Error(`${file}: GET ${url} → ${response.status}`)
  const markdown = await response.text()

  const sourceSha256 = createHash('sha256').update(markdown).digest('hex')
  const { buildVersion, checkers } = parseBundleDoc(markdown)
  const rules = [...new Set(checkers.flatMap((c) => c.rules))].sort()
  if (rules.length === 0) throw new Error(`${file}: parsed zero rule UIDs from ${url}`)
  const malformed = rules.filter((uid) => !UID.test(uid))
  if (malformed.length > 0) throw new Error(`${file}: malformed rule UIDs: ${malformed.join(', ')}`)

  // Compare by content, not by text: these files are Prettier-formatted on
  // commit, and a reflowed array is not a stale pin.
  const next = { ...manifest, buildVersion, sourceSha256, rules, checkers }
  if (JSON.stringify(next) === JSON.stringify(manifest)) {
    console.warn(`${file}: up to date (${rules.length} rules)`)
    continue
  }
  stale++
  if (CHECK_ONLY) {
    console.error(`${file}: STALE — re-run without --check`)
    continue
  }
  writeFileSync(path, JSON.stringify(next, null, 2) + '\n')
  console.warn(`${file}: refreshed (${rules.length} rules, ${checkers.length} checkers)`)
}

if (CHECK_ONLY && stale > 0) process.exit(1)
