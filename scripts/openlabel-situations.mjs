/**
 * OpenLABEL V1-0-0 situation catalogue for the sample data.
 *
 * Each entry describes one functional driving situation in the vocabulary the
 * v1 shapes in OMB (`artifacts/openlabel/openlabel.shacl.ttl`) can express:
 * ODD attributes, behaviour flags and road users. The families are inspired by
 * the situation classes of motorway automated lane keeping (nominal following,
 * lead-vehicle braking and cut-out reveals, cut-in and merging, stationary and
 * crossing targets, perception and environment disturbances, ODD boundaries,
 * emergency behaviour) plus a few non-motorway "contrast" situations that must
 * NOT match motorway queries. Wording and parameters are original.
 *
 * Attribute notation (property local names exactly as in the v1 shapes):
 *   - `true` / `false`          boolean flag (`xsd:boolean`)
 *   - `'ValueName'` / `[...]`   enumeration member(s), emitted as IRIs
 *   - `number` / `[min, max]`   boolean flag set to `true` PLUS its `<flag>Value`
 *                               (scalar, or a `schema:QuantitativeValue` range
 *                               where the v1 shape allows one)
 *
 * What v1 cannot express (driver state, system faults, transition demands,
 * lateral wandering within a lane) is deliberately absent — see
 * `apps/docs/ontology.md` ("OpenLABEL v1 vs v2").
 */

